// GET /scan: the scan page. Live mode reads the JPEG stream with fetch(),
// keeps it in memory, and shows the part received so far (browsers draw a
// truncated baseline JPEG from the top). Keep mode starts a 150 dpi scan on
// the printer and polls /scan/status until /scan/last.jpg is ready.
#pragma once

static const char SCAN_PAGE[] =
    "<!doctype html><html><head><meta charset=utf-8><meta name=viewport content='width=device-width'>"
    "<title>Scan</title><style>"
    "body{font-family:sans-serif;max-width:40em;margin:2em auto;padding:0 1em}"
    "fieldset{border:0;padding:0;margin:0 0 .8em}legend{font-weight:bold;padding:0;margin-bottom:.2em}"
    "label{margin-right:1.2em;white-space:nowrap}button{font-size:1em;padding:.4em 1.2em;margin-right:.4em}"
    "#bar{height:6px;background:#ddd;border-radius:3px;overflow:hidden;margin:1em 0 .4em}"
    "#bar div{height:100%;width:0;background:#2a7;transition:width .5s}"
    "#img{display:none;max-width:100%;margin-top:.8em;border:1px solid #ccc;background:#fff}"
    ".hint{color:#666;font-size:.9em}"
    "</style></head><body>"
    "<h1>Scan</h1><p><a href='/'>&larr; Printer status</a></p>"
    "<fieldset><legend>Mode</legend>"
    "<label><input type=radio name=mode value=stream checked> Live to this browser</label>"
    "<label><input type=radio name=mode value=last> Keep on the printer</label>"
    "<div class=hint id=hint></div></fieldset>"
    "<fieldset id=res><legend>Resolution</legend>"
    "<label><input type=radio name=dpi value=150> 150 dpi</label>"
    "<label><input type=radio name=dpi value=300 checked> 300 dpi</label>"
    "<label><input type=radio name=dpi value=600> 600 dpi (slow)</label></fieldset>"
    "<fieldset><legend>Paper</legend>"
    "<label><input type=radio name=paper value=a4 checked> A4</label>"
    "<label><input type=radio name=paper value=letter> Letter</label></fieldset>"
    "<p><button id=go>Scan</button><button id=stop disabled>Cancel</button> <a id=save hidden>Save</a></p>"
    "<div id=bar><div></div></div><p id=msg></p><img id=img alt='Scanned page'>"
    "<script>"
    "const $=i=>document.getElementById(i),val=n=>document.querySelector(`input[name=${n}]:checked`).value;"
    "let timer=null,live=false,url=null;"
    "const kb=n=>n<1048576?(n/1024).toFixed(0)+' KB':(n/1048576).toFixed(1)+' MB';"
    "function fname(){const d=new Date(),z=n=>String(n).padStart(2,'0');"
    "return `scan-${d.getFullYear()}${z(d.getMonth()+1)}${z(d.getDate())}-${z(d.getHours())}${z(d.getMinutes())}"
    "${z(d.getSeconds())}.jpg`}"
    "function hint(){const l=val('mode')==='last';$('res').style.display=l?'none':'';"
    "$('hint').textContent=l?'150 dpi. The scan stays on the printer until the next scan, so you can close this page.'"
    ":'The page appears here while it is scanned. Keep this page open until it is done.'}"
    "function busy(b){$('go').disabled=b;$('stop').disabled=!b;"
    "document.querySelectorAll('input').forEach(i=>i.disabled=b)}"
    "function say(t){$('msg').textContent=t}"
    "function show(st){const p=st.height?st.lines/st.height:0;$('bar').firstChild.style.width=(100*p).toFixed(1)+'%';"
    "if(st.state==='scanning')say(st.lines?`Scanning ${Math.round(100*p)}% (${kb(st.bytes)})`:'Warming up and calibrating\\u2026');"
    "else if(st.state==='done')say(`Done: ${st.width}\\u00d7${st.height} pixels at ${st.dpi} dpi, ${kb(st.bytes)}, ${st.elapsed.toFixed(0)} s`);"
    "else if(st.state==='failed')say('Scan failed: '+st.error);else if(st.state==='canceled')say('Canceled');}"
    "async function status(){try{const r=await fetch('/scan/status',{cache:'no-store'});return await r.json()}"
    "catch(e){return null}}"
    "function image(src,keep){$('img').src=src;$('img').style.display='block';"
    "if(keep){$('save').href=src;$('save').download=fname();$('save').hidden=false}}"
    "function poll(){clearInterval(timer);timer=setInterval(async()=>{const st=await status();if(!st)return;show(st);"
    "if(st.state!=='scanning'&&!live){clearInterval(timer);busy(false);"
    "if(st.mode==='last'&&st.state==='done'&&st.last)image('/scan/last.jpg?'+Date.now(),true)}},1000)}"
    "function preview(parts){const u=URL.createObjectURL(new Blob(parts,{type:'image/jpeg'})),old=url;url=u;"
    "image(u,false);if(old)setTimeout(()=>URL.revokeObjectURL(old),5000);return u}"
    "async function scanLive(){live=true;say('Starting\\u2026');const parts=[];"
    "try{const r=await fetch(`/scan/stream.jpg?dpi=${val('dpi')}&paper=${val('paper')}`,{cache:'no-store'});"
    "if(!r.ok){say(await r.text());return}"
    "poll();const rd=r.body.getReader();let t=0;"
    "for(;;){const {done,value}=await rd.read();if(done)break;parts.push(value);"
    "if(Date.now()-t>1500){t=Date.now();preview(parts)}}"
    "image(preview(parts),true)}catch(e){say('Connection lost: '+e.message)}"
    "finally{live=false;clearInterval(timer);const st=await status();if(st&&st.state!=='scanning')show(st);busy(false)}}"
    "async function scanLast(){say('Starting\\u2026');"
    "const r=await fetch(`/scan/last?paper=${val('paper')}`,{method:'POST'});"
    "if(!r.ok){say(await r.text());busy(false);return}poll()}"
    "$('go').onclick=()=>{busy(true);$('save').hidden=true;$('bar').firstChild.style.width='0';"
    "val('mode')==='last'?scanLast():scanLive()};"
    "$('stop').onclick=()=>fetch('/scan/cancel',{method:'POST'});"
    "document.querySelectorAll('input[name=mode]').forEach(i=>i.onchange=hint);hint();"
    "status().then(st=>{if(!st)return;if(!st.scanner){say('No scanner connected');$('go').disabled=true;return}"
    "if(st.state==='scanning'){busy(true);show(st);poll()}"
    "else if(st.last){say(`Kept on the printer: ${kb(st.last)} at 150 dpi`);image('/scan/last.jpg?'+Date.now(),true)}});"
    "</script></body></html>";
