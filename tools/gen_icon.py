#!/usr/bin/env python3
"""Draws the printer icon served at /icon.png (printer-icons) and writes it
as a C array to components/airprint/icon_png.h."""
import io
import os
from PIL import Image, ImageDraw

S = 128
im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
d = ImageDraw.Draw(im)
d.rounded_rectangle([30, 10, 98, 56], 4, fill=(250, 250, 250), outline=(120, 120, 120), width=3)    # paper in
d.rounded_rectangle([8, 44, 120, 100], 12, fill=(60, 64, 72))                                       # body
d.rounded_rectangle([8, 44, 120, 60], 8, fill=(84, 90, 100))
d.rectangle([28, 82, 100, 122], fill=(255, 255, 255), outline=(120, 120, 120), width=3)            # paper out
for i, c in enumerate([(0, 174, 239), (236, 0, 140), (255, 212, 0)]):                               # CMY stripes
    d.rectangle([38, 90 + i * 9, 90, 95 + i * 9], fill=c)
d.ellipse([100, 66, 110, 76], fill=(80, 220, 120))                                                  # status LED
buf = io.BytesIO()
im.save(buf, "PNG", optimize=True)
data = buf.getvalue()

out = os.path.join(os.path.dirname(__file__), "..", "components", "airprint", "icon_png.h")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_icon.py: 128x128 printer icon (printer-icons)\n#pragma once\n\n")
    f.write("static const unsigned char ICON_PNG[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
im.save(os.path.join(os.path.dirname(out), "..", "..", "host", "out", "icon.png")) if os.path.isdir(
    os.path.join(os.path.dirname(out), "..", "..", "host", "out")) else None
print("icon: %d bytes -> %s" % (len(data), out))
