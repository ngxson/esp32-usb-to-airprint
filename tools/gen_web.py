"""Build the web UI (web/, Svelte + Vite) and pack web/dist into
components/webui/web_assets.c: every file gzipped, as C arrays with its
Content-Type and an ETag.

Runs before every PlatformIO build (extra_scripts in platformio.ini) and from
host/Makefile; by hand: python3 tools/gen_web.py [--force]

The app is rebuilt (npm run build) when a file under web/ is newer than
web/dist/index.html, after `npm ci` if web/node_modules is missing. Without
Node.js an existing web/dist is used; with neither, the generated table is
empty and the server shows its plain status page.
"""
import gzip
import hashlib
import os
import shutil
import subprocess
import sys

try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
DIST = os.path.join(WEB, "dist")
OUT = os.path.join(ROOT, "components", "webui", "web_assets.c")

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json",
    ".webmanifest": "application/manifest+json",
    ".wasm": "application/wasm",
    ".woff2": "font/woff2",
}
SOURCES = ("src", "public", "index.html", "package.json", "package-lock.json", "vite.config.ts", "svelte.config.js",
           "tsconfig.json")


def log(msg):
    print("gen_web: " + msg, file=sys.stderr)


def newest_source():
    t = 0
    for name in SOURCES:
        p = os.path.join(WEB, name)
        if os.path.isfile(p):
            t = max(t, os.path.getmtime(p))
        for d, _, files in os.walk(p):
            for f in files:
                t = max(t, os.path.getmtime(os.path.join(d, f)))
    return t


def build(force):
    index = os.path.join(DIST, "index.html")
    stale = force or not os.path.exists(index) or newest_source() > os.path.getmtime(index)
    if not stale:
        return
    npm = shutil.which("npm")
    if not npm:
        log("npm not found: %s" % ("using the existing web/dist" if os.path.exists(index) else "no web UI"))
        return
    if not os.path.isdir(os.path.join(WEB, "node_modules")):
        log("npm ci")
        subprocess.check_call([npm, "ci", "--no-audit", "--no-fund"], cwd=WEB)
    log("npm run build")
    subprocess.check_call([npm, "run", "build", "--silent"], cwd=WEB)


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return "\n".join(lines)


def pack():
    files = []
    if os.path.isdir(DIST):
        for d, _, names in os.walk(DIST):
            for n in names:
                p = os.path.join(d, n)
                ext = os.path.splitext(n)[1].lower()
                if ext == ".map" or ext not in TYPES:
                    continue
                files.append(("/" + os.path.relpath(p, DIST).replace(os.sep, "/"), TYPES[ext], p))
    files.sort()
    out = ["// Generated by tools/gen_web.py from web/dist: do not edit.", '#include "webui.h"', ""]
    table = []
    total = 0
    for i, (path, ctype, src) in enumerate(files):
        raw = open(src, "rb").read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(gz)
        etag = '"%s"' % hashlib.sha1(raw).hexdigest()[:16]
        out.append("static const uint8_t A%d[] = {  // %s, %d bytes, %d gzipped" % (i, path, len(raw), len(gz)))
        out.append(c_bytes(gz))
        out.append("};")
        table.append('    {"%s", "%s", "\\"%s\\"", A%d, sizeof(A%d)},' % (path, ctype, etag.strip('"'), i, i))
    out.append("")
    out.append("const webui_asset_t WEBUI_ASSETS[] = {")
    out.extend(table)
    out.append("    {0},")
    out.append("};")
    text = "\n".join(out) + "\n"
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text != old:
        with open(OUT, "w") as f:
            f.write(text)
        log("%d files, %d KB gzipped -> %s" % (len(files), total // 1024, os.path.relpath(OUT, ROOT)))
    if not files:
        log("WARNING: no web UI (web/dist missing): the server shows its plain status page")


build("--force" in sys.argv)
pack()
